import {AbsoluteFill, Audio, OffthreadVideo, Sequence, interpolate, staticFile, useCurrentFrame} from 'remotion';
import {Caption, EndCard, Hook, Label} from './JacketAd';

// ~30s cut of JacketAd. Cuts only inside the speaker's pauses (found with ffmpeg silencedetect),
// so no sentence is broken: 0–17.4s (black) + 30.85–44.0s (navy).
export const A = {from: 0, to: 17.4};
export const B = {from: 30.85, to: 44.0};
const A_LEN = Math.round((A.to - A.from) * 30);
const B_LEN = Math.round((B.to - B.from) * 30);
export const XFADE = 8;
export const jacketAdShortDuration = A_LEN + B_LEN;

// Times in seconds on the short timeline.
export const CAPTIONS: Caption[] = [
  {from: 3.4, to: 8.0, ar: 'اللون الأوّل: أسود', en: 'Colour 1 · Black', swatch: '#1b1b1d'},
  {from: 13.0, to: 17.2, ar: 'ياقة فرو دافية', en: 'Warm fur collar'},
  {from: 17.8, to: 22.2, ar: 'اللون التاني: كحلي', en: 'Colour 2 · Navy', swatch: '#1f2c5a'},
  {from: 23.0, to: 27.2, ar: 'أي لون أحلى عليك؟ 🤔', en: 'Which colour is yours?'},
];

const SegmentB: React.FC = () => {
  const frame = useCurrentFrame();
  const opacity = interpolate(frame, [0, XFADE], [0, 1], {extrapolateRight: 'clamp'});
  return (
    <AbsoluteFill style={{opacity}}>
      <OffthreadVideo src={staticFile('media/jacket.mp4')} trimBefore={Math.round(B.from * 30)} style={{width: '100%', height: '100%', objectFit: 'cover'}} />
    </AbsoluteFill>
  );
};

export const JacketAdShort: React.FC = () => (
  <AbsoluteFill style={{background: 'black'}}>
    <Sequence durationInFrames={A_LEN}>
      <OffthreadVideo src={staticFile('media/jacket.mp4')} style={{width: '100%', height: '100%', objectFit: 'cover'}} />
    </Sequence>
    <Sequence from={A_LEN - XFADE} durationInFrames={B_LEN + XFADE}>
      <SegmentB />
    </Sequence>
    {/* Generated by: python3 scripts/make_soft_soundtrack.py 917 public/audio/jacket-short-bed.wav */}
    <Audio src={staticFile('audio/jacket-short-bed.wav')} volume={0.12} />
    <Hook />
    {CAPTIONS.map((c) => (
      <Label key={c.from} c={c} />
    ))}
    <EndCard start={(jacketAdShortDuration / 30 - 3.0) * 30} />
  </AbsoluteFill>
);
